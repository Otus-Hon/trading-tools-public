function seedMoneyFlowHistory(db) {
  const insertLong = db.prepare(`
    INSERT OR IGNORE INTO money_flow_long (
      date, weekday_zh, money_flow_million, underlying_last, underlying_pct_change, fetched_at_utc, source_url
    ) VALUES (?, ?, ?, ?, ?, ?, ?)
  `);
  const insertShort = db.prepare(`
    INSERT OR IGNORE INTO money_flow_short (
      date, weekday_zh, money_flow_million, underlying_last, underlying_pct_change, fetched_at_utc, source_url
    ) VALUES (?, ?, ?, ?, ?, ?, ?)
  `);
  const seed = db.transaction(() => {
    let longInserted = 0;
    let shortInserted = 0;
    for (const row of MONEY_FLOW_LONG_SEED) {
      longInserted += insertLong.run(...row, SEED_FETCHED_AT_UTC, SOURCE_URLS.long).changes;
    }
    for (const row of MONEY_FLOW_SHORT_SEED) {
      shortInserted += insertShort.run(...row, SEED_FETCHED_AT_UTC, SOURCE_URLS.short).changes;
    }
    db.prepare(`
      INSERT OR IGNORE INTO money_flow_long_meta
        (id, fetched_at_utc, source_url, sname, stime, total_mflow_raw, series)
      VALUES (1, ?, ?, ?, ?, NULL, 'long')
    `).run(SEED_FETCHED_AT_UTC, SOURCE_URLS.long, "恒生指數", "2026-10-20");
    db.prepare(`
      INSERT OR IGNORE INTO money_flow_short_meta
        (id, fetched_at_utc, source_url, sname, stime, total_mflow_raw, series)
      VALUES (1, ?, ?, ?, ?, NULL, 'short')
    `).run(SEED_FETCHED_AT_UTC, SOURCE_URLS.short, "恒生指數", "2026-10-20");
    return { longInserted, shortInserted };
  });
  return seed();
}

